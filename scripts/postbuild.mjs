// Hash every inline script in the built pages so the Worker's CSP allows them and nothing else.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;
const hashes = new Set();
for (const f of await readdir(dist)) {
  if (!f.endsWith('.html')) continue;
  const html = await readFile(join(dist, f), 'utf8');
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/application\/ld\+json/.test(m[1])) continue;
    hashes.add(`sha256-${createHash('sha256').update(m[2]).digest('base64')}`);
  }
}
const out = `// Generated by scripts/postbuild.mjs. Do not edit.\nexport const CSP_SCRIPT_HASHES = ${JSON.stringify([...hashes])};\n`;
await writeFile(new URL('../worker/csp.generated.js', import.meta.url), out);
console.log(`csp: ${hashes.size} inline script hash(es)`);
